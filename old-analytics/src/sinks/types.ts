// ── Session ─────────────────────────────────────────────────────────────────

/**
 * Emitted at session_start.  Git fields start null and are patched
 * asynchronously via SessionPatchEvent once `captureRepoSnapshot` resolves.
 * The SQLite sink upserts on `id` so the patch safely fills in the blanks.
 */
export type SessionStartEvent = {
  kind: "session_start";
  ts: number;
  /** Stable identifier for this session, generated by the hook. */
  id: string;
  parent_session_id: string | null;
  parent_session_file: string | null;
  started_at: number;
  cwd: string;
  pi_version: string;
  hostname: string;
  // git fields — initially null, filled by SessionPatchEvent
  repo_root: string | null;
  repo_remote: string | null;
  repo_owner: string | null;
  repo_name: string | null;
  branch_start: string | null;
  head_sha_start: string | null;
  dirty_at_start: number | null;
};

/**
 * Asynchronous update that fills in git fields after `captureRepoSnapshot`
 * resolves.  SqliteSink UPDATE-OR-IGNOREs on session_id.
 * T6 emits this shortly after SessionStartEvent to avoid blocking the session
 * start path on git I/O.
 */
export type SessionPatchEvent = {
  kind: "session_patch";
  ts: number;
  session_id: string;
  repo_root: string | null;
  repo_remote: string | null;
  repo_owner: string | null;
  repo_name: string | null;
  branch_start: string | null;
  head_sha_start: string | null;
  dirty_at_start: number | null;
};

/**
 * Emitted at session_shutdown.  Git end-state is captured synchronously
 * before this event fires.
 */
export type SessionEndEvent = {
  kind: "session_end";
  ts: number;
  session_id: string;
  ended_at: number;
  branch_end: string | null;
  head_sha_end: string | null;
  exit_reason: string | null;
};

// ── Branch ──────────────────────────────────────────────────────────────────

/**
 * Emitted when a `git checkout` / `git switch` is detected in a bash tool call
 * or (future) via external branch change detection.
 */
export type BranchTransitionEvent = {
  kind: "branch_transition";
  ts: number;
  session_id: string;
  turn_id: string | null;
  from_branch: string;
  to_branch: string;
};

// ── PR ───────────────────────────────────────────────────────────────────────

/**
 * Emitted when a PR is linked to a session.  Reason values and confidence
 * thresholds mirror PLAN.md *Multi-session → single PR linking*.
 */
export type PrAssociationEvent = {
  kind: "pr_association";
  ts: number;
  session_id: string;
  repo_remote: string;
  pr_number: number;
  pr_url: string;
  confidence: number;
  reason:
    | "commit-in-pr"
    | "ancestor-of-pr"
    | "branch-match"
    | "files-overlap"
    | "preceding-window";
};

// ── Prompt ───────────────────────────────────────────────────────────────────

/**
 * Emitted on `input`.  Raw prompt text is never stored by default
 * (`storePrompts = "hashed"`).  The `redacted` counter tracks any secrets
 * scrubbed by the hooks before the event is written.
 */
export type PromptEvent = {
  kind: "prompt";
  ts: number;
  id: string;
  session_id: string;
  source: string;
  /** First token if the input started with `/`, otherwise null. */
  command: string | null;
  /** Best-effort classification of the slash command type. */
  slash_kind: "extension" | "skill" | "template" | "builtin" | null;
  text_len: number;
  text_sha256: string;
  image_count: number;
  /**
   * Only present when `storePrompts = "full"` or `"summary"`.
   * Already redacted by the hook before inclusion.
   */
  text?: string;
  /** Redaction hits accumulated while processing this prompt, if any. */
  redacted?: RedactionHits;
};

// ── Turn ─────────────────────────────────────────────────────────────────────

/**
 * Emitted when a turn begins.  Model/thinking fields are included here
 * (denormalized) because `turns` is the primary query surface for these.
 */
export type TurnStartEvent = {
  kind: "turn_start";
  ts: number;
  id: string;
  session_id: string;
  prompt_id: string;
  /** 0-based index of this turn within its prompt. */
  idx: number;
  started_at: number;
  model_id: string | null;
  provider: string | null;
  thinking_level: string | null;
};

/**
 * Emitted when a turn completes.  The SQLite sink updates the existing row
 * (inserted at turn_start) with the end-state fields.
 */
export type TurnEndEvent = {
  kind: "turn_end";
  ts: number;
  turn_id: string;
  session_id: string;
  ended_at: number;
  model_id: string | null;
  provider: string | null;
  thinking_level: string | null;
  stop_reason: string | null;
};

/**
 * Emitted on `after_provider_response`.  Contains HTTP status and
 * normalised rate-limit headers.  SqliteSink updates the in-flight turn row.
 */
export type ProviderResponseEvent = {
  kind: "provider_response";
  ts: number;
  turn_id: string;
  session_id: string;
  http_status: number | null;
  /** Remaining request quota from `anthropic-ratelimit-requests-remaining` etc. */
  ratelimit_remaining: number | null;
  /** Unix ms until rate-limit resets (from `retry-after` or `*-reset`). */
  ratelimit_reset: number | null;
};

// ── LLM message ──────────────────────────────────────────────────────────────

/**
 * Emitted on `message_end` for `role === "assistant"`.  Carries the full
 * token usage and cost breakdown from `event.message.usage`.
 */
export type LlmMessageEvent = {
  kind: "llm_message";
  ts: number;
  id: string;
  turn_id: string;
  session_id: string;
  role: string;
  input_tokens: number;
  output_tokens: number;
  /** Tokens read from the prompt cache. */
  cache_read_tokens: number;
  /** Tokens written to the prompt cache. */
  cache_write_tokens: number;
  cost_input: number;
  cost_output: number;
  cost_cache_read: number;
  cost_cache_write: number;
  cost_total: number;
  /** Prompt-cache write retention observed on the provider request, if known. */
  cache_write_retention: "5m" | "1h" | null;
  time_to_first_token_ms: number | null;
  total_duration_ms: number | null;
  stop_reason: string | null;
  /**
   * The model id used for this response (e.g. "claude-sonnet-4-5").
   * Sourced from AssistantMessage.model — always present for real responses.
   * Nullable for NDJSON replay compatibility with pre-002 events.
   */
  model_id: string | null;
  /**
   * The provider name (e.g. "anthropic", "openai").
   * Nullable for NDJSON replay compatibility with pre-002 events.
   */
  provider: string | null;
};

