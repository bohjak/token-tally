/**
 * Mirrors the structure of config.json exactly.  All fields are required; the
 * extension entrypoint merges user config over these defaults before use.
 */
export type AnalyticsConfig = {
  local: {
    /** Whether the local SQLite + NDJSON storage is active. */
    enabled: boolean;
    /** Absolute or ~-prefixed path to the SQLite database file. */
    dbPath: string;
    /** Directory for per-day NDJSON append logs. */
    rawLogDir: string;
  };
  privacy: {
    /**
     * Controls how raw prompt text is stored.
     *   "full"   — store after redaction
     *   "hashed" — store sha256 + length only (default)
     *   "none"   — store neither text nor hash
     */
    storePrompts: "full" | "hashed" | "none";
    /**
     * Controls how tool input arguments are stored.
     *   "full"    — store after redaction
     *   "summary" — store first ~200 chars after redaction (default)
     *   "none"    — drop all arg content
     */
    storeToolArgs: "full" | "summary" | "none";
    /**
     * Controls how tool output text is stored.
     *   "full"      — store after redaction
     *   "size-only" — record byte count only, drop text (default)
     *   "none"      — drop even the byte count
     */
    storeToolOutputs: "full" | "size-only" | "none";
    /** User-supplied regex patterns (strings) compiled and added to default rules. */
    redactPatterns: string[];
  };
  git: {
    /** Enable git/PR capture at session boundaries and bash-tool detection. */
    enabled: boolean;
    /** Whether to call `gh pr view` at session_start to find the current PR. */
    fetchPR: boolean;
    /** Timeout in ms for `gh` CLI calls (keeps startup fast). */
    ghTimeoutMs: number;
  };
};

