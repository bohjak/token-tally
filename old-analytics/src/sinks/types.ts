/**
 * types.ts — Canonical shared contracts for the pi analytics extension.
 *
 * This file is the single source of truth for:
 *   - AnalyticsConfig     (mirrors config.json)
 *   - AnalyticsEvent      (discriminated union of every event kind)
 *   - AnalyticsSink       (interface all sinks implement)
 *   - MultiSink           (fan-out helper)
 *   - Type guards         (isSessionEvent, isTurnEvent, isToolEvent)
 *   - newId()             (shared UUID generator)
 *
 * **RULE: No other file may modify this file.**
 * Hooks emit events; sinks consume them; both import only from this module.
 *
 * T3 (redact module) exports `RedactionHits` and `StoredText`.  We import
 * them here with a type-only import so events can carry redaction metadata
 * inline.  If T3 has not finished yet when you run `tsc --noEmit`, you will
 * see "Cannot find module '../redact'" — that is expected during Wave 1
 * parallel execution; re-verify once all Wave 1 tasks are complete.
 *
 * Design note on `storeToolOutputs: "size-only"`:
 * The config allows "size-only" for tool outputs, which is not a valid
 * `PrivacyMode` in T3's privacy.ts (which uses "none"|"hashed"|"summary"|"full").
 * We keep "size-only" as a distinct literal in `AnalyticsConfig.privacy`
 * because it has a unique meaning (record byte count, drop all text — not even
 * a hash is needed).  The NdjsonSink (T5) handles this case separately before
 * calling `applyPrivacyMode`.
 */

