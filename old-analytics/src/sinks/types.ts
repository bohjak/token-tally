// ---------------------------------------------------------------------------
// Sink interface
// ---------------------------------------------------------------------------

/**
 * Every storage backend (SQLite, NDJSON, future OTLP) implements this
 * interface.  `write` is synchronous so the hot path never awaits storage —
 * sinks decide internally whether to buffer or write inline.
 */
export interface AnalyticsSink {
  /** Open connections, create directories, run migrations. */
  init(config: AnalyticsConfig): Promise<void>;
  /**
   * Record one event.  MUST NOT throw — callers do not try/catch this.
   * Implementations should catch their own errors and console.warn.
   */
  write(event: AnalyticsEvent): void;
  /** Flush any pending buffers.  No-op for synchronous sinks. */
  flush(): Promise<void>;
  /** Close connections / file handles gracefully. */
  close(): Promise<void>;
}

// ---------------------------------------------------------------------------
// MultiSink — fan-out helper
// ---------------------------------------------------------------------------

/**
 * Fans out write/flush/close to multiple sinks in order.
 * Errors from individual sinks are caught and console.warn'd so a broken
 * sink (e.g. full disk on NDJSON) cannot kill the SQLite path or the hot
 * path of pi itself.
 */
export class MultiSink implements AnalyticsSink {
  private readonly sinks: AnalyticsSink[];

  constructor(sinks: AnalyticsSink[]) {
    this.sinks = sinks;
  }

  async init(config: AnalyticsConfig): Promise<void> {
    for (const sink of this.sinks) {
      try {
        await sink.init(config);
      } catch (err) {
        console.warn("[analytics:MultiSink] init failed on a sink:", err);
      }
    }
  }

  write(event: AnalyticsEvent): void {
    for (const sink of this.sinks) {
      try {
        sink.write(event);
      } catch (err) {
        console.warn("[analytics:MultiSink] write failed on a sink:", err);
      }
    }
  }

  async flush(): Promise<void> {
    for (const sink of this.sinks) {
      try {
        await sink.flush();
      } catch (err) {
        console.warn("[analytics:MultiSink] flush failed on a sink:", err);
      }
    }
  }

  async close(): Promise<void> {
    for (const sink of this.sinks) {
      try {
        await sink.close();
      } catch (err) {
        console.warn("[analytics:MultiSink] close failed on a sink:", err);
      }
    }
  }
}

// ---------------------------------------------------------------------------
// Type guards
// ---------------------------------------------------------------------------

/**
 * True for events that map to the `sessions` table (start, patch, end).
 * Useful for sinks that maintain in-memory session state.
 */
export function isSessionEvent(
  e: AnalyticsEvent,
): e is SessionStartEvent | SessionPatchEvent | SessionEndEvent {
  return (
    e.kind === "session_start" ||
    e.kind === "session_patch" ||
    e.kind === "session_end"
  );
}

/**
 * True for events that map to the `turns` table or its related
 * `after_provider_response` row.
 */
export function isTurnEvent(
  e: AnalyticsEvent,
): e is TurnStartEvent | TurnEndEvent | ProviderResponseEvent {
  return (
    e.kind === "turn_start" ||
    e.kind === "turn_end" ||
    e.kind === "provider_response"
  );
}

/**
 * True for events that relate to tool execution or file I/O.
 */
export function isToolEvent(
  e: AnalyticsEvent,
): e is ToolCallEvent | FileTouchedEvent | ToolSideEffectEvent {
  return (
    e.kind === "tool_call" ||
    e.kind === "file_touched" ||
    e.kind === "tool_side_effect"
  );
}

/**
 * True for events that map to the `llm_messages` table.
 */
export function isLlmMessageEvent(e: AnalyticsEvent): e is LlmMessageEvent {
  return e.kind === "llm_message";
}

/**
 * True for events that relate to git activity (commits, branches, PRs).
 */
export function isGitEvent(
  e: AnalyticsEvent,
): e is CommitMadeEvent | BranchTransitionEvent | PrAssociationEvent {
  return (
    e.kind === "commit_made" ||
    e.kind === "branch_transition" ||
    e.kind === "pr_association"
  );
}

